"""Map cage NPC clones back to their explicit map models; no game writes."""
from pathlib import Path
import json,re,sys
root=Path(__file__).resolve().parents[1]
rows=json.loads((root/'data/reference/world/cage-bosses.json').read_text(encoding='utf8'))
groups=json.loads((root/'data/reference/world/cage-encounters.json').read_text(encoding='utf8'))
models={95300000+i:int(r['model'][1:]) for i,r in enumerate(rows)}
for group in groups['groups']:
 for r in group['members']:
  id=95300000+r['index'];model=int(r['model'][1:])
  assert id not in models or models[id]==model
  models[id]=model
source=(root/'src/spirit_npcs.rs').read_text()
private_sources={int(a) for a,b in re.findall(r'\((\d+),(\d+)\)',source) if 95300000<=int(a)<95301000}
assert set(models)==private_sources
text='// Generated by tools/build_spirit_models.py from cage model metadata.\npub const MODELS:&[(i32,i32)]=&[\n'+''.join(f' ({id},{m}),\n' for id,m in sorted(models.items()))+'];\n'
out=root/'src/spirit_cage_models.rs'
if '--check' in sys.argv:assert out.read_text()==text
else:out.write_text(text)
print(f'PASS: {len(models)} cage actor models cover every private source clone')
