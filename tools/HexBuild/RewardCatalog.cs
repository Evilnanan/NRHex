using SoulsFormats;

// Stable serialization IDs survive removing an ability from the active catalog.
static class RewardCatalog {
 public static readonly int[] HistoricalOwners=Enumerable.Range(1,27).Where(i=>i!=10).Select(i=>95000000+i*100).Concat(new[]{95002900,95003000,95003100}).ToArray();
 public const int Retired=95001900;
 public sealed record Entry(int Lot,int[] Order);
 public sealed record Serialized(int Lot,int[] Owners);
 public static int Table(int owner){int index=Array.IndexOf(HistoricalOwners,owner);if(index<0)throw new InvalidDataException("Unregistered reward ID");return 95110100+index;}
 // Two Red Envelope triples occupy 95410000/95410010. Preserve the legacy
 // prefix and skip both reserved groups when extending the ability pool.
 static int Lot(int group)=>95200000+group*10+(group>=21000?20:0);
 public static Entry[] Active(Hex[] hexes){
  var index=hexes.Select((h,i)=>(h.Id,i)).ToDictionary(v=>v.Id,v=>v.i);
  return AngelChant.Orders(HistoricalOwners.Length).Select((o,g)=>(o,g))
   .Where(v=>v.o.All(i=>index.ContainsKey(HistoricalOwners[i])))
   .Select(v=>new Entry(Lot(v.g),v.o.Select(i=>index[HistoricalOwners[i]]).ToArray())).ToArray();
 }
 // Only live triples need parameter rows. Retired placeholders would overflow
 // PARAM's 16-bit row count as the active catalog grows.
 public static Serialized[] ActiveSerialized(Hex[] hexes)=>Active(hexes).Select(e=>new Serialized(e.Lot,e.Order.Select(i=>hexes[i].Id).ToArray())).ToArray();
 public static HashSet<int> InactiveRows(Hex[] hexes){
  var available=hexes.Select(h=>h.Id).ToHashSet();
  return AngelChant.Orders(HistoricalOwners.Length).Select((o,g)=>(o,g)).Where(v=>v.o.Any(i=>!available.Contains(HistoricalOwners[i])))
   .SelectMany(v=>Enumerable.Range(0,3).Select(slot=>Lot(v.g)+slot)).ToHashSet();
 }
 public static Serialized[] Compatibility(Hex[] hexes){
  var available=hexes.Select(h=>h.Id).ToHashSet();
  return AngelChant.Orders(HistoricalOwners.Length).Select((o,g)=>{
   var owners=o.Select(i=>HistoricalOwners[i]).ToArray();
   for(int i=0;i<3;i++)if(!available.Contains(owners[i]))owners[i]=hexes.First(h=>!owners.Contains(h.Id)).Id;
   return new Serialized(Lot(g),owners);
  }).ToArray();
 }
 public static void Write(string path,Hex[] hexes){
  var entries=Active(hexes);
  if(entries.Length!=hexes.Length*(hexes.Length-1)*(hexes.Length-2))throw new InvalidDataException("Incomplete active pool");
  File.WriteAllText(path,"// Generated by RewardCatalog; native lot IDs remain stable across retirement.\n"+
   $"pub const HEX_COUNT: usize = {hexes.Length};\npub const OWNER_IDS: [i32; {hexes.Length}] = [{string.Join(",",hexes.Select(h=>h.Id))}];\npub const LEGACY_LOT_END:i32={Lot(HistoricalOwners.Length*(HistoricalOwners.Length-1)*(HistoricalOwners.Length-2))};\n"+
   $"pub static LOT_IDS:[i32;{entries.Length}]=["+string.Join(",",entries.Select(e=>e.Lot))+"];\n"+
   $"pub static ORDERS:[[usize;3];{entries.Length}]=[\n"+string.Join("\n",entries.Select(e=>$" [{string.Join(",",e.Order)}],"))+"\n];\n");
 }
}
