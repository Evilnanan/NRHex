using SoulsFormats;
// Stable per-ability references; exactly one three-row native spawn template.
static class RewardCatalog {
 public static readonly int[] HistoricalOwners=Enumerable.Range(1,27).Where(i=>i!=10).Select(i=>95000000+i*100).Concat(new[]{95002900,95003000,95003100,95003200,95003300,95003400,95003500,95003600,95003700,95003800,95003900,95004000,95004100,95004200,95004300}).ToArray();
 public const int Retired=95001900,TemplateLot=95200000;
 public sealed record Entry(int Lot,int[] Order);
 public sealed record Serialized(int Lot,int[] Owners);
 public const int HistoryFirst=96000000;
 public static int Table(int owner){int index=Array.IndexOf(HistoricalOwners,owner);if(index<0)throw new InvalidDataException("Register each new owner by appending HistoricalOwners");return 95110100+index;}
 public static int HistoryBit(int owner){int index=Array.IndexOf(HistoricalOwners,owner);if(index<0)throw new InvalidDataException("Unregistered history owner");return index;}
 public static int[] PackedIds(int slots)=>Enumerable.Range(0,(slots+7)/8).SelectMany(group=>Enumerable.Range(1,255).Select(value=>HistoryFirst+group*256+value)).ToArray();
 public static int LegacyHistory(int index)=>index<25?95002800+index:95002829+index-25;
 public static Serialized[] Template(Hex[] hexes){
  if(hexes.Length<3)throw new InvalidDataException("Need three template goods");
  return new[]{new Serialized(TemplateLot,hexes.Take(3).Select(h=>h.Id).ToArray())};
 }
 static InvalidOperationException RetiredStage()=>new("Full-permutation reward staging is retired; use --reward-template-stage or the current full build.");
 public static Entry[] Active(Hex[] hexes)=>throw RetiredStage();
 public static Serialized[] ActiveSerialized(Hex[] hexes)=>throw RetiredStage();
 public static Serialized[] Compatibility(Hex[] hexes)=>throw RetiredStage();
 public static HashSet<int> InactiveRows(Hex[] hexes)=>throw RetiredStage();
 public static void Write(string path,Hex[] hexes)=>WriteExpanded(path,hexes,HistoricalOwners);
 public static void WriteExpanded(string path,Hex[] hexes,int[] registry){
  var bits=hexes.Select(h=>Array.IndexOf(registry,h.Id)).ToArray();
  if(bits.Any(i=>i<0)||hexes.Select(h=>h.Id).Distinct().Count()!=hexes.Length||bits.Distinct().Count()!=hexes.Length)throw new InvalidDataException("Duplicate or unregistered ability/history slot");
  File.WriteAllText(path,"// Generated by RewardCatalog; runtime sampling uses a single native template.\n"+
   $"pub const HEX_COUNT:usize={hexes.Length};\npub const OWNER_IDS:[i32;HEX_COUNT]=[{string.Join(",",hexes.Select(h=>h.Id))}];\n"+
   $"pub const HISTORY_BITS:[usize;HEX_COUNT]=[{string.Join(",",bits)}];\npub const HISTORY_BYTES:usize={(registry.Length+7)/8};\npub const HISTORY_FIRST:i32={HistoryFirst};\n"+
   $"pub const TEMPLATE_LOT:i32={TemplateLot};\npub fn is_template_lot(lot:i32)->bool{{(TEMPLATE_LOT..TEMPLATE_LOT+3).contains(&lot)}}\n");
 }
}
